#!/bin/sh
# Runs a CI command on the checkout an attestor's check mounts at /work, in
# this image, as any uid, with no network and a read-only root:
#
#   pantheon-ci "soma build main.soma && test/edits.sh"
#
# It copies the checkout to /tmp/w, points Soma and opam at the image's
# prebuilt switches (Soma asks opam what a switch has, so it installs
# nothing), and runs the command there.
set -eu
export HOME=/tmp XDG_CACHE_HOME=/tmp/cache OPAMROOT=/home/pantheon/.opam SOMA_OCAML_SWITCH=/home/pantheon/.cache/soma/ocaml
# The root is read-only (docs/SECURITY-REVIEW-2.md P-3). opam writes its log
# even to list a switch: in /tmp, not $OPAMROOT/log.
export OPAMLOGS=/tmp/opam-logs
mkdir -p "$OPAMLOGS"
# What the switch has, as the image's build recorded it, under the name Soma
# looks for with SOMA_OCAML_SWITCH set (installed-MD5 of the switch's path),
# so a build doesn't ask opam each time
rec=$XDG_CACHE_HOME/soma/ocaml/installed-$(printf %s "$SOMA_OCAML_SWITCH" | md5sum | cut -c1-32)
if [ -s "$SOMA_OCAML_SWITCH/installed" ] && [ ! -e "$rec" ]; then
  mkdir -p "${rec%/*}" && cp "$SOMA_OCAML_SWITCH/installed" "$rec"
fi
cp -R /work /tmp/w
cd /tmp/w
# Pantheon commands are generated by deploy/ci-command.py on the trusted
# operator checkout. Keep their embedded policy intact: never load CI policy
# or test commands from /work. Other repositories supply their own commands.
exec sh -c "$1"
