#!/bin/sh
# A wg-quick config for this machine, from NETWORK/wg/*.json: a full mesh of
# the Pantheon machines, each allowed only its own VPN address. The private
# key is read from its file when the interface comes up, so the config itself
# holds no secret and can be regenerated any time a member changes.
#
#   scripts/net/wg-config.sh NETWORK NAME [KEYFILE] > /etc/wireguard/pantheon.conf
#   wg-quick up pantheon
#
# Then each agent's address in NETWORK/parts is its VPN IP and Pantheon port,
# for example 10.77.0.1:26700, and its node runs with --listen 10.77.0.1.
set -eu
net=${1:?usage: wg-config.sh NETWORK NAME [KEYFILE]} me=${2:?} keyf=${3:-/etc/wireguard/pantheon.key}
self=$net/wg/$me.json
[ -f "$self" ] || { echo "wg-config: no $self: run scripts/net/wg-keygen.sh on this machine and add its output there" >&2; exit 1; }
command -v jq >/dev/null || { echo "wg-config: needs jq" >&2; exit 1; }
endpoint=$(jq -r .endpoint "$self")
port=${endpoint##*:}; [ -n "$port" ] && [ "$port" != "$endpoint" ] || port=51820
printf '# generated by scripts/net/wg-config.sh for %s: regenerate it, do not edit it\n' "$me"
printf '[Interface]\nAddress = %s/24\nListenPort = %s\nPostUp = wg set %%i private-key %s\n' "$(jq -r .ip "$self")" "$port" "$keyf"
for f in "$net"/wg/*.json; do
  [ "$f" = "$self" ] && continue
  printf '\n# %s\n[Peer]\nPublicKey = %s\nAllowedIPs = %s/32\nPersistentKeepalive = 25\n' "$(jq -r .name "$f")" "$(jq -r .pubkey "$f")" "$(jq -r .ip "$f")"
  e=$(jq -r .endpoint "$f"); [ -n "$e" ] && printf 'Endpoint = %s\n' "$e"
done
